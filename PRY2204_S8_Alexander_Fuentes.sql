-- INFORME 1
-- Mecanicos sin bono de jefatura y con impuesto inferior a $40.000.
SELECT
    cod_mecanico AS "ID MECANICO",
    pnombre || ' ' || apaterno AS "NOMBRE MECANICO",
    sueldo AS "SALARIO",
    monto_impuesto AS "IMPUESTO ACTUAL",
    ROUND(monto_impuesto * 0.80) AS "IMPUESTO REBAJADO",
    sueldo - ROUND(monto_impuesto * 0.80) AS "SUELDO CON REBAJA IMPUESTOS"
FROM MECANICO
WHERE bono_jefatura IS NULL
  AND monto_impuesto < 40000
ORDER BY monto_impuesto DESC, apaterno ASC;

-- INFORME 2
-- Sueldo entre $600.000 y $900.000, O mecanicos sin supervisor.
SELECT
    cod_mecanico AS "IDENTIFICADOR",
    TRIM(pnombre || ' ' || NVL(snombre || ' ','') || apaterno) AS "MECANICO",
    sueldo AS "SALARIO ACTUAL",
    ROUND(sueldo * 0.05) AS "AJUSTE",
    sueldo + ROUND(sueldo * 0.05) AS "SUELDO_REAJUSTADO"
FROM MECANICO
WHERE sueldo BETWEEN 600000 AND 900000
   OR cod_supervisor IS NULL
ORDER BY sueldo ASC,
         TRIM(pnombre || ' ' || NVL(snombre || ' ','') || apaterno) DESC;

