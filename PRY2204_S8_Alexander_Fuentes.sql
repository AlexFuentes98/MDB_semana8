CREATE TABLE PAIS (
    id_pais NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 9 INCREMENT BY 3),
    nom_pais VARCHAR2(50) NOT NULL,
    CONSTRAINT pais_pk PRIMARY KEY (id_pais),
    CONSTRAINT pais_nom_un UNIQUE (nom_pais)
);

CREATE TABLE CIUDAD (
    id_ciudad NUMBER(5) NOT NULL,
    nom_ciudad VARCHAR2(50) NOT NULL,
    cod_pais NUMBER NOT NULL,
    CONSTRAINT ciudad_pk PRIMARY KEY (id_ciudad),
    CONSTRAINT ciudad_pais_fk FOREIGN KEY (cod_pais)
        REFERENCES PAIS(id_pais)
);

CREATE TABLE SUCURSAL (
    cod_sucursal CHAR(3) NOT NULL,
    nom_sucursal VARCHAR2(60) NOT NULL,
    calle VARCHAR2(80) NOT NULL,
    num_calle NUMBER(6) NOT NULL,
    cod_ciudad NUMBER(5) NOT NULL,
    CONSTRAINT sucursal_pk PRIMARY KEY (cod_sucursal),
    CONSTRAINT sucursal_ciudad_fk FOREIGN KEY (cod_ciudad)
        REFERENCES CIUDAD(id_ciudad)
);

CREATE TABLE SERVICIO (
    id_servicio NUMBER(5) NOT NULL,
    descripcion VARCHAR2(100) NOT NULL,
    costo NUMBER(10) NOT NULL,
    CONSTRAINT servicio_pk PRIMARY KEY (id_servicio),
    CONSTRAINT servicio_costo_ck CHECK (costo > 0)
);

CREATE TABLE MARCA (
    id_marca NUMBER(5) NOT NULL,
    nom_marca VARCHAR2(50) NOT NULL,
    CONSTRAINT marca_pk PRIMARY KEY (id_marca),
    CONSTRAINT marca_nom_un UNIQUE (nom_marca)
);

CREATE TABLE MODELO (
    id_modelo NUMBER(5) NOT NULL,
    id_marca NUMBER(5) NOT NULL,
    descripcion VARCHAR2(80) NOT NULL,
    CONSTRAINT modelo_pk PRIMARY KEY (id_modelo, id_marca),
    CONSTRAINT modelo_marca_fk FOREIGN KEY (id_marca)
        REFERENCES MARCA(id_marca)
);

CREATE TABLE TIPO_AUTOMOVIL (
    id_tipo CHAR(1) NOT NULL,
    descripcion VARCHAR2(50) NOT NULL,
    CONSTRAINT tipo_automovil_pk PRIMARY KEY (id_tipo)
);

CREATE TABLE CLIENTE (
    rut NUMBER(8) NOT NULL,
    dv CHAR(1) NOT NULL,
    pnombre VARCHAR2(30) NOT NULL,
    snombre VARCHAR2(30),
    apaterno VARCHAR2(30) NOT NULL,
    amaterno VARCHAR2(30),
    telefono VARCHAR2(20),
    email VARCHAR2(100),
    CONSTRAINT cliente_pk PRIMARY KEY (rut)
);

CREATE TABLE ESTANDAR (
    rut NUMBER(8) NOT NULL,
    puntaje_fidelidad NUMBER(8) DEFAULT 0 NOT NULL,
    CONSTRAINT estandar_pk PRIMARY KEY (rut),
    CONSTRAINT estandar_cliente_fk FOREIGN KEY (rut)
        REFERENCES CLIENTE(rut)
);

CREATE TABLE PREMIUM (
    rut NUMBER(8) NOT NULL,
    puntos_cliente NUMBER(8) DEFAULT 0 NOT NULL,
    monto_credito NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT premium_pk PRIMARY KEY (rut),
    CONSTRAINT premium_cliente_fk FOREIGN KEY (rut)
        REFERENCES CLIENTE(rut)
);

CREATE TABLE AUTOMOVIL (
    patente CHAR(6) NOT NULL,
    anio NUMBER(4) NOT NULL,
    cant_puertas NUMBER(1),
    color VARCHAR2(30),
    rut_cliente NUMBER(8) NOT NULL,
    id_tipo CHAR(1) NOT NULL,
    id_modelo NUMBER(5) NOT NULL,
    id_marca NUMBER(5) NOT NULL,
    CONSTRAINT automovil_pk PRIMARY KEY (patente),
    CONSTRAINT automovil_cliente_fk FOREIGN KEY (rut_cliente)
        REFERENCES CLIENTE(rut),
    CONSTRAINT automovil_tipo_fk FOREIGN KEY (id_tipo)
        REFERENCES TIPO_AUTOMOVIL(id_tipo),
    CONSTRAINT automovil_modelo_fk FOREIGN KEY (id_modelo, id_marca)
        REFERENCES MODELO(id_modelo, id_marca),
    CONSTRAINT automovil_puertas_ck CHECK (cant_puertas IS NULL OR cant_puertas BETWEEN 2 AND 6)
);

CREATE TABLE MECANICO (
    cod_mecanico NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 460 INCREMENT BY 7),
    pnombre VARCHAR2(30) NOT NULL,
    snombre VARCHAR2(30),
    apaterno VARCHAR2(30) NOT NULL,
    amaterno VARCHAR2(30),
    bono_jefatura NUMBER(10),
    sueldo NUMBER(10) NOT NULL,
    monto_impuesto NUMBER(10) NOT NULL,
    cod_supervisor NUMBER,
    CONSTRAINT mecanico_pk PRIMARY KEY (cod_mecanico),
    CONSTRAINT mecanico_supervisor_fk FOREIGN KEY (cod_supervisor)
        REFERENCES MECANICO(cod_mecanico)
);

CREATE TABLE MANTENCION (
    num_mantencion NUMBER(6) NOT NULL,
    cod_sucursal CHAR(3) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_salida DATE,
    patente_auto CHAR(6),
    cod_mecanico NUMBER NOT NULL,
    costo_total NUMBER(12),
    estado VARCHAR2(15) NOT NULL,
    CONSTRAINT mantencion_pk PRIMARY KEY (num_mantencion),
    CONSTRAINT mant_sucursal_fk FOREIGN KEY (cod_sucursal)
        REFERENCES SUCURSAL(cod_sucursal),
    CONSTRAINT mant_auto_fk FOREIGN KEY (patente_auto)
        REFERENCES AUTOMOVIL(patente),
    CONSTRAINT mant_mecanico_fk FOREIGN KEY (cod_mecanico)
        REFERENCES MECANICO(cod_mecanico)
);

CREATE TABLE DETALLE_SERVICIO (
    num_mantencion NUMBER(6) NOT NULL,
    cod_sucursal CHAR(3) NOT NULL,
    id_servicio NUMBER(5) NOT NULL,
    cantidad NUMBER(4) DEFAULT 1 NOT NULL,
    CONSTRAINT detalle_servicio_pk
        PRIMARY KEY (num_mantencion, cod_sucursal, id_servicio),
    CONSTRAINT detalle_servicio_serv_fk FOREIGN KEY (id_servicio)
        REFERENCES SERVICIO(id_servicio)
);

